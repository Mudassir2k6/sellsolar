/**
 * Filter dealers by city, search query, registration source, and verification status.
 */
export function getFilteredDealers({
  dealers = VERIFIED_DEALERS,
  city = '',
  search = '',
  source = 'all',
  verifiedOnly = false
} = {}) {
  return dealers.filter((dealer) => {
    // City filter
    if (city && city.trim() !== '' && dealer.city?.toLowerCase() !== city.trim().toLowerCase()) {
      return false;
    }

    // Source filter (backend / registration source)
    if (source && source !== 'all' && dealer.registration_source !== source) {
      return false;
    }

    // Verification filter
    if (verifiedOnly && !dealer.is_verified_dealer) {
      return false;
    }

    // Search query
    if (search && search.trim() !== '') {
      const q = search.trim().toLowerCase();
      const matchName = dealer.full_name?.toLowerCase().includes(q);
      const matchBiz = dealer.business_name?.toLowerCase().includes(q);
      const matchAddr = dealer.business_address?.toLowerCase().includes(q);
      const matchCity = dealer.city?.toLowerCase().includes(q);
      const matchPhone = dealer.phone?.includes(q);
      const matchBrands = Array.isArray(dealer.brands) && dealer.brands.some((b) => b.toLowerCase().includes(q));
      const matchSpecs = dealer.specialties?.toLowerCase().includes(q);

      if (!matchName && !matchBiz && !matchAddr && !matchCity && !matchPhone && !matchBrands && !matchSpecs) {
        return false;
      }
    }

    return true;
  });
}

/**
 * Count dealers grouped by city
 */
export function getCityDealerCounts(dealers = VERIFIED_DEALERS) {
  const counts = {};
  for (const d of dealers) {
    if (d.city) {
      counts[d.city] = (counts[d.city] || 0) + 1;
    }
  }
  return counts;
}

/**
 * Count dealers grouped by registration source
 */
export function getSourceDealerCounts(dealers = VERIFIED_DEALERS) {
  const counts = { all: dealers.length, ai_curated: 0, self_registered: 0, manual_admin: 0 };
  for (const d of dealers) {
    const src = d.registration_source || 'ai_curated';
    if (counts[src] !== undefined) {
      counts[src] += 1;
    }
  }
  return counts;
}
