export function formatPKR(price: number): string {
  if (price >= 10000000) {
    return `Rs ${(price / 10000000).toFixed(2)} Cr`;
  }
  if (price >= 100000) {
    return `Rs ${(price / 100000).toFixed(1)} Lac`;
  }
  return `Rs ${price.toLocaleString('en-PK')}`;
}

